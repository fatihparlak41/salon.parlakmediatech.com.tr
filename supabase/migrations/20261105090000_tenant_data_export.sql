-- Faz SAAS.1C.2b - secure tenant data export (Owner only).
--
-- WHAT THIS ADDS (and nothing else): two PRIVATE tables (request/token state, append-only audit) and six SECURITY DEFINER RPCs. It changes no
-- existing table, policy, grant or trigger; subscription / protection / tenant status, plans, branches, booking, appointments, customers and
-- billing enforcement are untouched. The export is deliberately NOT gated by billing state (active / trial / grace / read_only all may export).
--
-- MODEL
--   * Owner only: an ACTIVE membership of the tenant whose live role holds permissions.manage_unrestricted (only the SALON_OWNER template carries it).
--     Authorization never reads user_metadata and never trusts a client-supplied role/tenant: the tenant of a download is read from the token row.
--   * Fresh authentication: the caller's SIGNED access token must carry an `amr` entry whose timestamp is at most 15 minutes old. PostgREST has already
--     verified the JWT signature; the claim is read from request.jwt.claims. Missing / malformed / stale -> denied (fail closed).
--   * Download token: 256-bit random value generated by the APP; only its sha256 hex is stored here. Single use (atomic UPDATE under a row lock), max
--     10 minutes, bound to the actor AND the tenant. Every failure of the consume step is the SAME generic result (no enumeration).
--   * Rate limit: 3 successful exports per rolling 24 h per tenant. A request RESERVES its slot, so concurrent requests cannot exceed the cap; the
--     check runs under a per-tenant advisory lock. Failed / expired attempts do not consume quota but are capped (10 per rolling 24 h) so a broken
--     client cannot hammer the endpoint; only ONE export may be active (pending or downloading) per tenant.
--   * Audit: append-only, no customer data, no raw token, counts + byte size + error code only. Denials are RETURNED (not raised) so that their
--     audit row survives the transaction.
--   * Data is read page by page by STABLE definer functions; every page re-validates actor, tenant, owner status and the 30 minute download window.
--     Rows created after the snapshot fence are excluded so the archive never contains a child without its parent.

create schema if not exists private;

-- ---------------------------------------------------------------------------------------------------------------------------------------------
-- tables (private schema: not exposed through the API; RLS enabled with NO policy; every API role stripped of every privilege)
-- ---------------------------------------------------------------------------------------------------------------------------------------------
create table private.tenant_export_requests (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants (id) on delete cascade,
  actor_id uuid not null,
  client_request_id uuid not null,
  requested_at timestamptz not null default now(),
  status text not null default 'pending' check (status in ('pending', 'downloading', 'completed', 'failed', 'expired')),
  token_hash text not null check (token_hash ~ '^[0-9a-f]{64}$'),
  token_expires_at timestamptz not null,
  token_consumed_at timestamptz,
  fence_at timestamptz,
  completed_at timestamptz,
  entity_counts jsonb,
  archive_bytes bigint check (archive_bytes is null or archive_bytes >= 0),
  error_code text check (error_code is null or error_code ~ '^[a-z0-9_]{1,40}$'),
  constraint tenant_export_requests_token_window check (token_expires_at > requested_at and token_expires_at <= requested_at + interval '10 minutes'),
  constraint tenant_export_requests_token_hash_uk unique (token_hash),
  constraint tenant_export_requests_client_request_uk unique (actor_id, client_request_id)
);
create unique index tenant_export_requests_one_active_uidx on private.tenant_export_requests (tenant_id) where status in ('pending', 'downloading');
create index tenant_export_requests_tenant_time_idx on private.tenant_export_requests (tenant_id, requested_at desc);
alter table private.tenant_export_requests enable row level security;

create table private.tenant_export_audit (
  id bigint generated always as identity primary key,
  occurred_at timestamptz not null default now(),
  request_id uuid,
  tenant_id uuid,
  actor_id uuid,
  event text not null check (event in ('requested', 'denied', 'downloaded', 'completed', 'failed')),
  error_code text check (error_code is null or error_code ~ '^[a-z0-9_]{1,40}$'),
  entity_counts jsonb,
  archive_bytes bigint check (archive_bytes is null or archive_bytes >= 0)
);
create index tenant_export_audit_tenant_time_idx on private.tenant_export_audit (tenant_id, occurred_at desc);
alter table private.tenant_export_audit enable row level security;

