-- TRUE only when the signed JWT proves an authentication event (password, otp, magic link, oauth, sso, totp, webauthn) within the last 15 minutes.
create or replace function private.export_fresh_auth()
returns boolean
language plpgsql
stable
set search_path = ''
as $$
declare
  v_claims jsonb;
  v_ts bigint;
begin
  begin
    v_claims := nullif(current_setting('request.jwt.claims', true), '')::jsonb;
  exception when others then
    return false;
  end;
  if v_claims is null or jsonb_typeof(v_claims -> 'amr') is distinct from 'array' then
    return false;
  end if;
  select max((e ->> 'timestamp')::bigint) into v_ts
    from jsonb_array_elements(v_claims -> 'amr') e
   where jsonb_typeof(e) = 'object'
     and e ->> 'method' in ('password', 'otp', 'magiclink', 'oauth', 'sso/saml', 'totp', 'webauthn')
     and (e ->> 'timestamp') ~ '^[0-9]{1,12}$';
  if v_ts is null then
    return false;
  end if;
  return v_ts <= extract(epoch from now())::bigint + 60 and extract(epoch from now())::bigint - v_ts <= 900;
end;
$$;
revoke all on function private.export_fresh_auth() from public, anon, authenticated, service_role;

