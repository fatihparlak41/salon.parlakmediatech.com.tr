-- ---------------------------------------------------------------------------------------------------------------------------------------------
-- 4/5. report the outcome (completion counts toward the 3-per-24h quota; a failure does not)
-- ---------------------------------------------------------------------------------------------------------------------------------------------
create or replace function public.complete_tenant_export(p_request_id uuid, p_counts jsonb, p_bytes bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_r private.tenant_export_requests%rowtype;
begin
  if v_actor is null then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;
  select * into v_r from private.tenant_export_requests r where r.id = p_request_id for update;
  if not found or v_r.actor_id <> v_actor or v_r.status <> 'downloading' then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;
  if not private.export_counts_valid(p_counts) or p_bytes is null or p_bytes < 0 or p_bytes > 4294967296 then
    return jsonb_build_object('ok', false, 'error', 'invalid_report');
  end if;
  update private.tenant_export_requests
     set status = 'completed', completed_at = now(), entity_counts = p_counts, archive_bytes = p_bytes
   where id = v_r.id;
  perform private.export_audit(v_r.id, v_r.tenant_id, v_actor, 'completed', null, p_counts, p_bytes);
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.fail_tenant_export(p_request_id uuid, p_error_code text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_r private.tenant_export_requests%rowtype;
  v_code text := coalesce(nullif(p_error_code, ''), 'export_failed');
begin
  if v_actor is null then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;
  select * into v_r from private.tenant_export_requests r where r.id = p_request_id for update;
  if not found or v_r.actor_id <> v_actor or v_r.status not in ('pending', 'downloading') then
    return jsonb_build_object('ok', false, 'error', 'not_allowed');
  end if;
  if v_code !~ '^[a-z0-9_]{1,40}$' then
    v_code := 'export_failed';
  end if;
  update private.tenant_export_requests set status = 'failed', completed_at = now(), error_code = v_code where id = v_r.id;
  perform private.export_audit(v_r.id, v_r.tenant_id, v_actor, 'failed', v_code, null, null);
  return jsonb_build_object('ok', true);
end;
$$;

-- ---------------------------------------------------------------------------------------------------------------------------------------------
-- 6. what the Owner screen shows (Owner only; anyone else gets a bare refusal - no other tenant detail)
-- ---------------------------------------------------------------------------------------------------------------------------------------------
create or replace function public.get_tenant_export_status(p_tenant_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_done integer;
  v_last timestamptz;
  v_oldest timestamptz;
  v_active boolean;
begin
  if v_actor is null or not private.export_is_owner(p_tenant_id, v_actor) then
    return jsonb_build_object('allowed', false);
  end if;
  select count(*) filter (where r.completed_at > now() - interval '24 hours'), max(r.completed_at), min(r.completed_at) filter (where r.completed_at > now() - interval '24 hours')
    into v_done, v_last, v_oldest
    from private.tenant_export_requests r where r.tenant_id = p_tenant_id and r.status = 'completed';
  select exists (select 1 from private.tenant_export_requests r where r.tenant_id = p_tenant_id
                  and ((r.status = 'pending' and r.token_expires_at > now()) or (r.status = 'downloading' and r.fence_at > now() - interval '30 minutes'))) into v_active;
  return jsonb_build_object('allowed', true, 'remaining', greatest(3 - v_done, 0), 'limit', 3, 'last_export_at', v_last,
    'next_available_at', case when v_done >= 3 then v_oldest + interval '24 hours' else null end,
    'in_progress', v_active, 'fresh_auth', private.export_fresh_auth());
end;
$$;

