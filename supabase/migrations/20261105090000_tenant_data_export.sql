-- counts may only be an object of whitelisted section names with non-negative integers (so no free text / PII can ever reach the audit).
create or replace function private.export_counts_valid(p_counts jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select p_counts is not null and jsonb_typeof(p_counts) = 'object'
    and not exists (
      select 1 from jsonb_each(p_counts) kv
       where kv.key !~ '^[a-z_]{1,40}$' or jsonb_typeof(kv.value) <> 'number' or (kv.value)::text !~ '^[0-9]{1,12}$'
    );
$$;
revoke all on function private.export_counts_valid(jsonb) from public, anon, authenticated, service_role;

-- ---------------------------------------------------------------------------------------------------------------------------------------------
-- 1. request an export (reserves the quota slot; returns a result code - never raises for an audited denial)
-- ---------------------------------------------------------------------------------------------------------------------------------------------
create or replace function public.request_tenant_export(p_tenant_id uuid, p_token_hash text, p_client_request_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_id uuid;
  v_done integer;
  v_failed integer;
  v_oldest timestamptz;
  v_expires timestamptz;
begin
  if v_actor is null then
    return jsonb_build_object('ok', false, 'error', 'unauthenticated');
  end if;
  if p_tenant_id is null or p_client_request_id is null or p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    return jsonb_build_object('ok', false, 'error', 'invalid_request');
  end if;

  -- one writer per tenant at a time: closes the rate-limit race
  perform pg_advisory_xact_lock(hashtextextended('tenant_export:' || p_tenant_id::text, 0));

  if not private.export_is_owner(p_tenant_id, v_actor) then
    perform private.export_audit(null, p_tenant_id, v_actor, 'denied', 'not_owner', null, null);
    return jsonb_build_object('ok', false, 'error', 'not_owner');
  end if;
  if not private.export_fresh_auth() then
    perform private.export_audit(null, p_tenant_id, v_actor, 'denied', 'fresh_auth_required', null, null);
    return jsonb_build_object('ok', false, 'error', 'fresh_auth_required');
  end if;

  if exists (select 1 from private.tenant_export_requests r where r.actor_id = v_actor and r.client_request_id = p_client_request_id) then
    return jsonb_build_object('ok', false, 'error', 'duplicate_request');
  end if;

  -- sweep: an unused token past its expiry, or a download that never reported back for 30 minutes, is closed as a failed attempt
  update private.tenant_export_requests
     set status = 'expired', error_code = 'token_expired'
   where tenant_id = p_tenant_id and status = 'pending' and token_expires_at <= now();
  update private.tenant_export_requests
     set status = 'failed', error_code = 'abandoned', completed_at = now()
   where tenant_id = p_tenant_id and status = 'downloading' and fence_at <= now() - interval '30 minutes';

  if exists (select 1 from private.tenant_export_requests r where r.tenant_id = p_tenant_id and r.status in ('pending', 'downloading')) then
    perform private.export_audit(null, p_tenant_id, v_actor, 'denied', 'export_in_progress', null, null);
    return jsonb_build_object('ok', false, 'error', 'export_in_progress');
  end if;

  select count(*), min(r.completed_at) into v_done, v_oldest
    from private.tenant_export_requests r
   where r.tenant_id = p_tenant_id and r.status = 'completed' and r.completed_at > now() - interval '24 hours';
  if v_done >= 3 then
    perform private.export_audit(null, p_tenant_id, v_actor, 'denied', 'rate_limited', null, null);
    return jsonb_build_object('ok', false, 'error', 'rate_limited', 'retry_at', v_oldest + interval '24 hours');
  end if;

  select count(*) into v_failed
    from private.tenant_export_requests r
   where r.tenant_id = p_tenant_id and r.status in ('failed', 'expired') and r.requested_at > now() - interval '24 hours';
  if v_failed >= 10 then
    perform private.export_audit(null, p_tenant_id, v_actor, 'denied', 'too_many_failures', null, null);
    return jsonb_build_object('ok', false, 'error', 'too_many_failures');
  end if;

  v_expires := now() + interval '10 minutes';
  insert into private.tenant_export_requests (tenant_id, actor_id, client_request_id, token_hash, token_expires_at)
  values (p_tenant_id, v_actor, p_client_request_id, p_token_hash, v_expires)
  returning id into v_id;
  perform private.export_audit(v_id, p_tenant_id, v_actor, 'requested', null, null, null);
  return jsonb_build_object('ok', true, 'request_id', v_id, 'expires_at', v_expires, 'remaining_after', 3 - v_done - 1);
end;
$$;

-- ---------------------------------------------------------------------------------------------------------------------------------------------
-- 2. consume the single-use token (every failure is the same generic result)
-- ---------------------------------------------------------------------------------------------------------------------------------------------
create or replace function public.consume_tenant_export_token(p_token_hash text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_r private.tenant_export_requests%rowtype;
  v_fence timestamptz := clock_timestamp();
begin
  if v_actor is null then
    return jsonb_build_object('ok', false, 'error', 'invalid_token');
  end if;
  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    perform private.export_audit(null, null, v_actor, 'denied', 'invalid_token', null, null);
    return jsonb_build_object('ok', false, 'error', 'invalid_token');
  end if;

  select * into v_r from private.tenant_export_requests r where r.token_hash = p_token_hash for update;
  if not found
     or v_r.actor_id <> v_actor
     or v_r.status <> 'pending'
     or v_r.token_consumed_at is not null
     or v_r.token_expires_at <= now()
     or not private.export_is_owner(v_r.tenant_id, v_actor) then
    -- the audit row never names a tenant here: the caller may not be entitled to learn that the token exists
    perform private.export_audit(null, null, v_actor, 'denied', 'invalid_token', null, null);
    return jsonb_build_object('ok', false, 'error', 'invalid_token');
  end if;

  update private.tenant_export_requests
     set status = 'downloading', token_consumed_at = now(), fence_at = v_fence
   where id = v_r.id;
  perform private.export_audit(v_r.id, v_r.tenant_id, v_actor, 'downloaded', null, null, null);
  return jsonb_build_object('ok', true, 'request_id', v_r.id, 'fence_at', v_fence,
    'tenant_timezone', (select t.timezone from public.tenants t where t.id = v_r.tenant_id),
    'tenant_currency', (select t.currency from public.tenants t where t.id = v_r.tenant_id));
end;
$$;

-- ---------------------------------------------------------------------------------------------------------------------------------------------
-- 3. read one page of one section (keyset pagination; explicit column lists: nothing is exported by SELECT *)
-- ---------------------------------------------------------------------------------------------------------------------------------------------
create or replace function public.export_read_section(p_request_id uuid, p_section text, p_after text default null, p_limit integer default 500)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_r private.tenant_export_requests%rowtype;
  v_t uuid;
  v_f timestamptz;
  v_a1 uuid;
  v_a2 uuid;
  v_z constant uuid := '00000000-0000-0000-0000-000000000000';
  v_lim integer := least(greatest(coalesce(p_limit, 500), 1), 1000);
  v_rows jsonb;
  v_next text;
  v_n integer;
begin
  if v_actor is null then
    raise exception 'export_denied' using errcode = '42501';
  end if;
  select * into v_r from private.tenant_export_requests r where r.id = p_request_id;
  if not found or v_r.actor_id <> v_actor or v_r.status <> 'downloading' or v_r.fence_at is null or v_r.fence_at <= now() - interval '30 minutes'
     or not private.export_is_owner(v_r.tenant_id, v_actor) then
    raise exception 'export_denied' using errcode = '42501';
  end if;
  v_t := v_r.tenant_id;
  v_f := v_r.fence_at;
  begin
    v_a1 := nullif(split_part(coalesce(p_after, ''), '|', 1), '')::uuid;
    v_a2 := nullif(split_part(coalesce(p_after, ''), '|', 2), '')::uuid;
  exception when others then
    raise exception 'invalid_cursor' using errcode = '22023';
  end;

  -- every page selects rows whose key ordering is (k1, k2); k2 is the zero uuid for single-key tables
  if p_section = 'tenant' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.name, t.slug, t.timezone, t.currency, t.created_at,
                   t.customer_cancellation_enabled, t.customer_cancellation_cutoff_minutes, t.customer_reschedule_enabled, t.customer_reschedule_cutoff_minutes
              from public.tenants t where t.id = v_t and t.created_at <= v_f and (v_a1 is null) order by t.id limit v_lim) x;
  elsif p_section = 'branches' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.name, t.address, t.phone, t.whatsapp_phone, t.instagram_handle, t.location_url, t.is_primary, t.created_at, t.updated_at, t.deleted_at
              from public.branches t where t.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or t.id > v_a1) order by t.id limit v_lim) x;
  elsif p_section = 'staff' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.full_name, t.email, t.phone, t.color, t.status, t.display_order, t.concurrent_capacity, t.created_at, t.updated_at, t.deleted_at
              from public.staff_members t where t.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or t.id > v_a1) order by t.id limit v_lim) x;
  elsif p_section = 'staff_branches' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1, x.k2), '[]'::jsonb), count(*), (array_agg(x.k1::text || '|' || x.k2::text order by x.k1 desc, x.k2 desc))[1]
      into v_rows, v_n, v_next
      from (select t.staff_member_id k1, t.branch_id k2, t.staff_member_id, t.branch_id, t.created_at
              from public.staff_branches t join public.staff_members s on s.id = t.staff_member_id
             where s.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or (t.staff_member_id, t.branch_id) > (v_a1, coalesce(v_a2, v_z)))
             order by t.staff_member_id, t.branch_id limit v_lim) x;
  elsif p_section = 'staff_services' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1, x.k2), '[]'::jsonb), count(*), (array_agg(x.k1::text || '|' || x.k2::text order by x.k1 desc, x.k2 desc))[1]
      into v_rows, v_n, v_next
      from (select t.staff_member_id k1, t.service_id k2, t.staff_member_id, t.service_id, t.created_at
              from public.staff_services t join public.staff_members s on s.id = t.staff_member_id
             where s.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or (t.staff_member_id, t.service_id) > (v_a1, coalesce(v_a2, v_z)))
             order by t.staff_member_id, t.service_id limit v_lim) x;
  elsif p_section = 'service_branches' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1, x.k2), '[]'::jsonb), count(*), (array_agg(x.k1::text || '|' || x.k2::text order by x.k1 desc, x.k2 desc))[1]
      into v_rows, v_n, v_next
      from (select t.service_id k1, t.branch_id k2, t.service_id, t.branch_id, t.created_at
              from public.service_branches t join public.services s on s.id = t.service_id
             where s.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or (t.service_id, t.branch_id) > (v_a1, coalesce(v_a2, v_z)))
             order by t.service_id, t.branch_id limit v_lim) x;
  elsif p_section = 'staff_schedules' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.staff_member_id, t.branch_id, t.weekday, t.start_time, t.end_time, t.created_at, t.updated_at, t.deleted_at
              from public.staff_schedules t where t.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or t.id > v_a1) order by t.id limit v_lim) x;
  elsif p_section = 'staff_schedule_exceptions' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.staff_member_id, t.exception_date, t.type, t.start_time, t.end_time, t.reason, t.created_at, t.updated_at, t.deleted_at
              from public.staff_schedule_exceptions t where t.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or t.id > v_a1) order by t.id limit v_lim) x;
  elsif p_section = 'services' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.category, t.name, t.description, t.duration_minutes, t.price, t.status, t.display_order, t.pricing_mode, t.booking_mode, t.price_public,
                   t.display_duration_min, t.display_duration_max, t.public_summary, t.public_details, t.preparation_note, t.aftercare_note, t.important_note, t.badge_label,
                   t.rebook_min_days, t.rebook_max_days, t.created_at, t.updated_at, t.deleted_at
              from public.services t where t.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or t.id > v_a1) order by t.id limit v_lim) x;
  elsif p_section = 'customers' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.full_name, t.phone, t.email, t.notes, t.status, t.created_at, t.updated_at, t.deleted_at
              from public.customers t where t.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or t.id > v_a1) order by t.id limit v_lim) x;
  elsif p_section = 'appointments' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
      from (select t.id k1, v_z k2, t.id, t.branch_id, t.customer_id, t.status, t.notes, t.source, t.scheduled_start_at, t.scheduled_end_at, t.created_at, t.updated_at
              from public.appointments t where t.tenant_id = v_t and t.created_at <= v_f and (v_a1 is null or t.id > v_a1) order by t.id limit v_lim) x;
  elsif p_section = 'appointment_items' then
    select coalesce(jsonb_agg(to_jsonb(x) - 'k1' - 'k2' order by x.k1), '[]'::jsonb), count(*), (array_agg(x.k1::text order by x.k1 desc))[1]
      into v_rows, v_n, v_next
