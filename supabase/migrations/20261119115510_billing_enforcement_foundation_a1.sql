create or replace function private.billing_enforcement_config_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op <> 'UPDATE' then
    raise exception 'billing_enforcement_config is a singleton and cannot be deleted or truncated';
  end if;
  if coalesce(current_setting('salonos.enforcement_setter', true), '') <> 'on' then
    raise exception 'billing_enforcement_config changes only through admin_set_billing_enforcement_stage';
  end if;
  if new.id is distinct from old.id then
    raise exception 'billing_enforcement_config id is fixed';
  end if;
  return new;
end;
$$;
create trigger billing_enforcement_config_guard before update or delete on private.billing_enforcement_config
  for each row execute function private.billing_enforcement_config_guard();
create trigger billing_enforcement_config_no_truncate before truncate on private.billing_enforcement_config
  for each statement execute function private.billing_enforcement_config_guard();

-- a change that did NOT come through the setter (an operator deliberately set the marker) still leaves an audit row: there is no unaudited stage change
create or replace function private.billing_enforcement_config_audit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (old.stage is distinct from new.stage or old.version is distinct from new.version)
     and coalesce(current_setting('salonos.enforcement_event_written', true), '') <> 'on' then
    insert into private.billing_enforcement_events (event, actor_id, from_stage, to_stage, reason, request_id, request_hash, version_before, version_after)
    values ('stage_change', coalesce(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid), old.stage, new.stage,
            'direct operator change without the setter', gen_random_uuid(), 'direct', old.version, new.version);
  end if;
  return null;
end;
$$;
create trigger billing_enforcement_config_audit after update on private.billing_enforcement_config
  for each row execute function private.billing_enforcement_config_audit();

