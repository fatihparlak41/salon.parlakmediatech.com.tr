create or replace function public.admin_billing_enforcement_preflight(p_target_stage integer, p_expected_protected integer default null, p_app_sha text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid;
  v_res jsonb;
  v_run bigint;
begin
  perform private.admin_require_owner();
  v_actor := auth.uid();
  if p_target_stage is null or p_target_stage not between 0 and 4 then
    raise exception 'invalid_target_stage';
  end if;
  if p_app_sha is not null and p_app_sha !~ '^[0-9a-f]{7,40}$' then
    raise exception 'invalid_app_sha';
  end if;
  v_res := private.billing_preflight_core(p_target_stage::smallint, p_expected_protected, p_app_sha);
  insert into private.billing_preflight_runs (actor_id, target_stage, config_version, result_hash, passed, summary)
  values (v_actor, p_target_stage, (v_res ->> 'configVersion')::integer, v_res ->> 'hash', (v_res ->> 'passed')::boolean,
          jsonb_build_object('checks', (select jsonb_agg(jsonb_build_object('id', c ->> 'id', 'pass', (c ->> 'pass')::boolean)) from jsonb_array_elements(v_res -> 'checks') c),
                             'context', v_res -> 'context'))
  returning id into v_run;
  return v_res || jsonb_build_object('runId', v_run, 'expiresAt', now() + interval '15 minutes');
end;
$$;

create or replace function public.admin_set_billing_enforcement_stage(p_target_stage integer, p_expected_stage integer, p_expected_version integer, p_reason text,
                                                                      p_request_id uuid, p_preflight_hash text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid;
  v_reason text;
  v_hash text;
  v_cfg private.billing_enforcement_config%rowtype;
  v_prev private.billing_enforcement_events%rowtype;
  v_run private.billing_preflight_runs%rowtype;
  v_fresh jsonb;
  v_event bigint;
  v_from smallint;
begin
  perform private.admin_require_owner();
  v_actor := auth.uid();
  if p_request_id is null then
    raise exception 'request_id_required';
  end if;
  if p_target_stage is null or p_target_stage not between 0 and 4 then
    raise exception 'invalid_target_stage';
  end if;
  if p_expected_stage is null or p_expected_version is null then
    raise exception 'expected_state_required';
  end if;
  v_reason := btrim(coalesce(p_reason, ''));
  if char_length(v_reason) < 10 or char_length(v_reason) > 500 then
    raise exception 'reason_required';
  end if;
  v_hash := encode(sha256(convert_to(p_target_stage || '|' || p_expected_stage || '|' || p_expected_version || '|' || v_reason || '|' || coalesce(p_preflight_hash, ''), 'UTF8')), 'hex');

  -- one writer at a time (also serialises concurrent attempts of the same request id)
  select * into v_cfg from private.billing_enforcement_config where id = 1 for update;
  v_from := v_cfg.stage;

  select * into v_prev from private.billing_enforcement_events e where e.actor_id = v_actor and e.request_id = p_request_id and e.event = 'stage_change';
  if found then
    if v_prev.request_hash = v_hash then
      return jsonb_build_object('ok', true, 'replayed', true, 'eventId', v_prev.id, 'fromStage', v_prev.from_stage, 'stage', v_prev.to_stage, 'version', v_prev.version_after);
    end if;
    return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'request_id_conflict');
  end if;

  if v_cfg.stage <> p_expected_stage then
    return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'stale_stage');
  end if;
  if v_cfg.version <> p_expected_version then
    return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'stale_version');
  end if;
  if p_target_stage = v_cfg.stage then
    return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'no_change');
  end if;

  if p_target_stage > v_cfg.stage then
    if p_target_stage <> v_cfg.stage + 1 then
      return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'multi_step_denied');
    end if;
    if p_preflight_hash is null then
      return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, null, 'preflight_required');
    end if;
    select * into v_run from private.billing_preflight_runs r
     where r.actor_id = v_actor and r.target_stage = p_target_stage and r.result_hash = p_preflight_hash and r.config_version = v_cfg.version
       and r.at > now() - interval '15 minutes'
     order by r.at desc limit 1;
    if not found then
      return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'preflight_stale');
    end if;
    -- the world must still look the way it did when the preflight ran: recompute with the same operator context and compare the verdict hash
    v_fresh := private.billing_preflight_core(p_target_stage::smallint, nullif(v_run.summary -> 'context' ->> 'expectedProtected', '')::integer, v_run.summary -> 'context' ->> 'appSha');
    if v_fresh ->> 'hash' is distinct from p_preflight_hash then
      return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'preflight_stale');
    end if;
    if not v_run.passed or not (v_fresh ->> 'passed')::boolean then
      return private.billing_enforcement_refuse(v_actor, v_from, p_target_stage::smallint, v_reason, p_request_id, v_hash, v_cfg.version, p_preflight_hash, 'preflight_failed');
    end if;
  end if;

  -- apply: the event first (so its id is stored on the config row), then the config change under the setter marker
  insert into private.billing_enforcement_events (event, actor_id, from_stage, to_stage, reason, request_id, request_hash, version_before, version_after, preflight_hash)
  values ('stage_change', v_actor, v_cfg.stage, p_target_stage, v_reason, p_request_id, v_hash, v_cfg.version, v_cfg.version + 1, p_preflight_hash)
  returning id into v_event;
  perform set_config('salonos.enforcement_setter', 'on', true);
  perform set_config('salonos.enforcement_event_written', 'on', true);
  update private.billing_enforcement_config
     set stage = p_target_stage, version = version + 1, stage_changed_at = now(), updated_at = now(), updated_by = v_actor, last_event_id = v_event
   where id = 1;
  perform set_config('salonos.enforcement_setter', '', true);
  perform set_config('salonos.enforcement_event_written', '', true);
  return jsonb_build_object('ok', true, 'replayed', false, 'eventId', v_event, 'fromStage', v_from, 'stage', p_target_stage, 'version', v_cfg.version + 1);
end;
$$;

