-- Faz SAAS.1C.2c-A1 - INERT billing-enforcement foundation (control plane only).
--
-- WHAT THIS IS: the control plane for a future, staged billing enforcement: the stage configuration (default 0 = OFF), the stage setter and its append-only audit,
-- a reusable preflight, the action registry (source of truth for "every API-reachable write path is classified"), the pure decision / protected short-circuit
-- model, and the empty counter / shadow tables the later stages will fill.
--
-- WHAT THIS IS NOT (and the tests prove it): no existing function, trigger, policy, grant or table is changed; no write path calls any function below; nothing in
-- the product reads the stage. At stage 0 (the only stage this migration can leave behind) installing it changes ZERO salon behaviour. The guards and triggers
-- on the 75 business write functions / 22 direct table operations are A2.
--
-- Stages: 0 OFF, 1 SHADOW, 2 PUBLIC_BOOKING, 3 NEW_BUSINESS_WRITES, 4 FULL_ENFORCEMENT.
-- Authorization: the two operator RPCs are platform OWNER only (private.admin_require_owner(): auth.uid() + an active platform_admins row with role 'owner'),
-- executable by `authenticated` only (never anon / PUBLIC / service_role). Everything else is private (no API privilege, RLS on, no policy).
-- Precedence for the effective access (documented and tested): deleted tenant > protected subscription > tenant lifecycle (suspended / canceled) > subscription dates.
-- A protected tenant is therefore always full unless it is deleted; the existing lifecycle RPCs already refuse to suspend / cancel a protected tenant, so the two
-- rules only ever disagree after a direct operator write, and then protection wins (the tenant is never blocked by BILLING enforcement).

create schema if not exists private;

