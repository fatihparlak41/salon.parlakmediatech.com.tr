-- The canonical protection rule. deleted > protected > lifecycle / dates. The existing access-state function is NOT modified; this wraps it.
create or replace function private.billing_effective_access(p_tenant_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_deleted timestamptz;
  v_prot boolean;
  v_raw jsonb;
begin
  select t.deleted_at into v_deleted from public.tenants t where t.id = p_tenant_id;
  if not found then
    return null;
  end if;
  select coalesce(s.protected, false) into v_prot from public.subscriptions s where s.tenant_id = p_tenant_id;
  v_prot := coalesce(v_prot, false);
  v_raw := private.tenant_access_state(p_tenant_id);
  if v_deleted is not null then
    return jsonb_build_object('mode', 'blocked', 'reason', 'tenant_deleted', 'protected', v_prot, 'deleted', true, 'precedence', 'deleted',
                              'rawMode', v_raw ->> 'mode', 'rawReason', v_raw ->> 'reason');
  end if;
  if v_prot then
    return jsonb_build_object('mode', 'full', 'reason', 'protected', 'protected', true, 'deleted', false, 'precedence', 'protected',
                              'rawMode', v_raw ->> 'mode', 'rawReason', v_raw ->> 'reason');
  end if;
  return jsonb_build_object('mode', v_raw ->> 'mode', 'reason', v_raw ->> 'reason', 'protected', false, 'deleted', false, 'precedence', 'access_state',
                            'rawMode', v_raw ->> 'mode', 'rawReason', v_raw ->> 'reason');
end;
$$;

-- decision = f(effective access, category policy, stage). `policy` is the full (stage 4) verdict used by shadow reporting; `enforced` says whether the stage
-- would really refuse it. Before stage 4 a blocked tenant is treated like read_only. Stage 0 never decides anything (allow / stage_off).
create or replace function private.billing_decide(p_tenant_id uuid, p_category text, p_stage smallint default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_stage smallint := coalesce(p_stage, private.billing_stage());
  v_cat private.billing_categories%rowtype;
  v_eff jsonb;
  v_mode text;
  v_policy text;
  v_raw_policy text;
  v_effective_mode text;
  v_enforced boolean;
  v_decision text;
  v_reason text;
  v_code text;
begin
  v_eff := private.billing_effective_access(p_tenant_id);
  if v_eff is null then
    return jsonb_build_object('decision', 'allow', 'enforced', false, 'policy', 'allow', 'reason', 'tenant_not_found', 'stage', v_stage, 'category', p_category,
                              'policyMiss', false, 'protectedOverride', false);
  end if;
  select * into v_cat from private.billing_categories where category = p_category;
  if not found then
    return jsonb_build_object('decision', 'allow', 'enforced', false, 'policy', 'allow', 'reason', 'unknown_category', 'stage', v_stage, 'category', p_category,
                              'mode', v_eff ->> 'mode', 'policyMiss', true, 'protectedOverride', false);
  end if;
  v_mode := v_eff ->> 'mode';
  v_policy := case v_mode when 'read_only' then v_cat.read_only when 'blocked' then v_cat.blocked else 'allow' end;
  v_raw_policy := case v_eff ->> 'rawMode' when 'read_only' then v_cat.read_only when 'blocked' then v_cat.blocked else 'allow' end;
  v_effective_mode := case when v_mode = 'blocked' and v_stage < 4 then 'read_only' else v_mode end;
  v_enforced := v_stage >= 2 and v_stage >= v_cat.first_stage
                and (case v_effective_mode when 'read_only' then v_cat.read_only when 'blocked' then v_cat.blocked else 'allow' end) = 'block';
  v_code := case when v_policy <> 'block' then null
                 when p_category = 'PUBLIC_BOOKING_CREATE' then 'BL003'
                 when v_mode = 'blocked' then 'BL002'
                 else 'BL001' end;
  if v_stage = 0 then
    v_decision := 'allow'; v_reason := 'stage_off'; v_enforced := false;
  elsif v_enforced then
    v_decision := 'blocked'; v_reason := v_eff ->> 'reason';
  elsif v_policy = 'block' then
    v_decision := 'would_block'; v_reason := v_eff ->> 'reason';
  else
    v_decision := 'allow'; v_reason := v_eff ->> 'reason';
  end if;
  return jsonb_build_object('decision', v_decision, 'enforced', v_enforced, 'policy', v_policy, 'reason', v_reason, 'code', v_code, 'stage', v_stage,
                            'category', p_category, 'mode', v_mode, 'protected', (v_eff ->> 'protected')::boolean,
                            'protectedOverride', (v_eff ->> 'protected')::boolean and v_raw_policy = 'block' and v_policy = 'allow', 'policyMiss', false);
end;
$$;

-- counters read model (no PII): totals over one stage since a time
create or replace function private.billing_enforcement_counters(p_stage smallint, p_since timestamptz)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'decisions', coalesce((select sum(c.n) from private.billing_decision_counters c where c.stage = p_stage and c.day >= p_since::date), 0),
    'allow', coalesce((select sum(c.n) from private.billing_decision_counters c where c.stage = p_stage and c.day >= p_since::date and c.decision = 'allow'), 0),
    'would_block', coalesce((select sum(c.n) from private.billing_decision_counters c where c.stage = p_stage and c.day >= p_since::date and c.decision = 'would_block'), 0),
    'blocked', coalesce((select sum(c.n) from private.billing_decision_counters c where c.stage = p_stage and c.day >= p_since::date and c.decision = 'blocked'), 0),
    'guard_errors', coalesce((select sum(h.n) from private.billing_guard_health h where h.kind = 'guard_error' and h.day >= p_since::date), 0),
    'policy_misses', coalesce((select sum(h.n) from private.billing_guard_health h where h.kind = 'policy_miss' and h.day >= p_since::date), 0),
    'unknown_category', coalesce((select sum(h.n) from private.billing_guard_health h where h.kind = 'unknown_category' and h.day >= p_since::date), 0),
    'protected_would_block', coalesce((select sum(h.n) from private.billing_guard_health h where h.kind = 'protected_would_block' and h.day >= p_since::date), 0));
$$;

-- ---------------------------------------------------------------------------------------------------------------------------------------------
-- 6. registry completeness scan (catalog based): which API-reachable write paths are NOT in the registry?
-- ---------------------------------------------------------------------------------------------------------------------------------------------
create or replace function private.billing_registry_unregistered()
returns table (kind text, action_key text)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_tables text[];
  v_roles text[];
  v_names text[];
  v_src text[];
  v_low text[];
  v_exposed boolean[];
  v_writer boolean[];
  v_seen text[] := '{}';
  n integer;
  i integer;
  j integer;
  v_changed boolean;
  rec record;
  r_role text;
begin
  select coalesce(array_agg(c.relname::text), '{}') into v_tables
    from pg_class c where c.relkind in ('r', 'p') and c.relnamespace in ('public'::regnamespace, 'private'::regnamespace);
  select coalesce(array_agg(o.rolname::text), '{}') into v_roles from pg_roles o where o.rolname in ('anon', 'authenticated', 'service_role', 'booking_gateway');
  select array_agg(p.proname::text order by p.proname, p.oid),
         array_agg(pg_get_functiondef(p.oid) order by p.proname, p.oid),
         array_agg((p.pronamespace = 'public'::regnamespace and exists (select 1 from unnest(v_roles) rr where has_function_privilege(rr, p.oid, 'execute'))) order by p.proname, p.oid)
    into v_names, v_src, v_exposed
    from pg_proc p where p.prokind = 'f' and p.pronamespace in ('public'::regnamespace, 'private'::regnamespace);
  n := coalesce(array_length(v_names, 1), 0);
  if n = 0 then
    return;
  end if;
  v_writer := array_fill(false, array[n]);
  v_low := array_fill(''::text, array[n]);
  for i in 1..n loop
    v_low[i] := lower(v_src[i]);
    for rec in select regexp_matches(v_src[i], '\m(insert\s+into|delete\s+from|update)\s+(?:(?:public|private)\.)?"?([a-z_][a-z0-9_]*)', 'gi') as mm loop
      if lower(rec.mm[2]) = any (v_tables) then
        v_writer[i] := true;
        exit;
      end if;
    end loop;
  end loop;
  loop
    v_changed := false;
    for i in 1..n loop
      if not v_writer[i] then
        for j in 1..n loop
          if v_writer[j] and v_names[j] <> v_names[i] and position('.' || v_names[j] || '(' in v_low[i]) > 0 then
            v_writer[i] := true;
            v_changed := true;
            exit;
          end if;
        end loop;
      end if;
    end loop;
    exit when not v_changed;
  end loop;
  for i in 1..n loop
    if v_exposed[i] and v_writer[i] and not (v_names[i] = any (v_seen))
       and not exists (select 1 from private.billing_action_registry r where r.action_key = 'fn:' || v_names[i]) then
      v_seen := v_seen || v_names[i];
      kind := 'function';
      action_key := 'fn:' || v_names[i];
      return next;
    end if;
  end loop;
  -- direct table writes available to an API role (table-level or any column-level privilege)
  for rec in select c.relname::text as tname, c.oid as toid from pg_class c where c.relkind in ('r', 'p') and c.relnamespace = 'public'::regnamespace order by 1 loop
    foreach r_role in array v_roles loop
      if has_table_privilege(r_role, rec.toid, 'INSERT') and not exists (select 1 from private.billing_action_registry r where r.action_key = 'table:' || rec.tname || ':INSERT')
         and not (('table:' || rec.tname || ':INSERT') = any (v_seen)) then
        v_seen := v_seen || ('table:' || rec.tname || ':INSERT');
        kind := 'table_op'; action_key := 'table:' || rec.tname || ':INSERT'; return next;
      end if;
      if has_any_column_privilege(r_role, rec.toid, 'UPDATE') and not exists (select 1 from private.billing_action_registry r where r.action_key = 'table:' || rec.tname || ':UPDATE')
         and not (('table:' || rec.tname || ':UPDATE') = any (v_seen)) then
        v_seen := v_seen || ('table:' || rec.tname || ':UPDATE');
        kind := 'table_op'; action_key := 'table:' || rec.tname || ':UPDATE'; return next;
      end if;
      if has_table_privilege(r_role, rec.toid, 'DELETE') and not exists (select 1 from private.billing_action_registry r where r.action_key = 'table:' || rec.tname || ':DELETE')
         and not (('table:' || rec.tname || ':DELETE') = any (v_seen)) then
        v_seen := v_seen || ('table:' || rec.tname || ':DELETE');
        kind := 'table_op'; action_key := 'table:' || rec.tname || ':DELETE'; return next;
      end if;
    end loop;
  end loop;
  return;
end;
$$;

