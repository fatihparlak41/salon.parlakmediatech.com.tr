async function rollbackProbe<T>(fn: (sql: Sql) => Promise<T>): Promise<T> {
  let out: T | undefined;
  await testDb
    .begin(async (sql) => {
      out = await fn(sql);
      throw new Error("ROLLBACK_PROBE");
    })
    .catch((e: Error) => {
      if (e.message !== "ROLLBACK_PROBE") throw e;
    });
  return out as T;
}

